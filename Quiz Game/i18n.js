let currentLang = localStorage.getItem('quizBattle_lang') || 'en';

function t(key, ...args) {
  const dict = I18N[currentLang] || I18N.en;
  let text = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (args.length > 0) {
    args.forEach((val, idx) => {
      text = text.replace(new RegExp(`\\{${idx}\\}`, 'g'), val);
    });
  }
  return text;
}

function applyTranslations(lang) {
  currentLang = lang;
  localStorage.setItem('quizBattle_lang', lang);
  document.documentElement.lang = lang;

  document.title = t('docTitle');

  const langTextEl = document.getElementById('lang-text');
  if (langTextEl) {
    langTextEl.textContent = lang.toUpperCase();
  }
  const langToggleBtn = document.getElementById('lang-toggle');
  if (langToggleBtn) {
    langToggleBtn.title = t('langToggleTitle');
  }

  const themeToggleBtn = document.getElementById('theme-toggle');
  if (themeToggleBtn) {
    themeToggleBtn.title = t('themeToggleTitle');
  }
  const audioToggleBtn = document.getElementById('audio-toggle');
  if (audioToggleBtn) {
    audioToggleBtn.title = t('audioToggleTitle');
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key) {
      el.innerHTML = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      el.title = t(key);
    }
  });

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function setLanguage(lang) {
  applyTranslations(lang === 'vi' ? 'vi' : 'en');
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'vi' : 'en';
  setLanguage(nextLang);
  return nextLang;
}

function getLanguage() {
  return currentLang;
}

if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.t = t;
  window.setLanguage = setLanguage;
  window.toggleLanguage = toggleLanguage;
  window.getLanguage = getLanguage;
  
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyTranslations(currentLang));
  } else {
    applyTranslations(currentLang);
  }
}
